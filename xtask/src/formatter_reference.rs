use std::fmt::Write;
use std::fs;
use std::path::Path;

use bray_formatter::{FormatterRule, FormatterStage};

use crate::workspace;

const REFERENCE_PATH: &str = "docs/tools/formatter-rules.md";

pub(crate) fn run(mut arguments: impl Iterator<Item = String>) -> Result<(), String> {
    let check = match arguments.next().as_deref() {
        None => false,
        Some("check") => {
            crate::command::reject_trailing_argument(arguments)?;

            true
        }
        Some(action) => return Err(format!("unexpected formatter reference command: {action}")),
    };

    update(&workspace::root()?, check)
}

fn update(root: &Path, check: bool) -> Result<(), String> {
    let path = root.join(REFERENCE_PATH);
    let expected = reference();

    if check {
        let actual = fs::read_to_string(&path)
            .map_err(|error| format!("could not read {}: {error}", path.display()))?;

        if actual != expected {
            return Err(
                "formatter reference is stale, run cargo xtask format reference".to_owned(),
            );
        }
    } else {
        fs::write(&path, expected)
            .map_err(|error| format!("could not write {}: {error}", path.display()))?;
    }

    Ok(())
}

fn reference() -> String {
    let mut output = String::from(
        "# Formatter rule reference\n\n\
         <!-- Generated by cargo xtask format reference. -->\n\n\
         This reference is generated from `FormatterRule::descriptor()` in `bray-formatter`.\n\n\
         Stages run in the order below. Earlier stages constrain later decisions. Within each stage,\n\
         lower explicit rule order wins. Rule orders are unique within a stage. Conflicting owner\n\
         pairs are recorded once. A shared decision without a recorded conflict is an invariant failure.\n\n\
         Dependencies apply to the named decision only. Disabling a dependency preserves other decisions\n\
         owned by the rule. Disabling a spacing rule preserves source spacing at its selected boundary.\n\n",
    );

    output.push_str("## Precedence stages\n\n");

    for stage in FormatterStage::ALL {
        write!(output, "- `{stage:?}`:").expect("writing to a string cannot fail");

        if *stage == FormatterStage::RecoveryPreservation {
            output.push_str(" preserve recovered source before any configurable rule.\n");
        } else {
            let names = FormatterRule::in_stage(*stage)
                .iter()
                .map(|rule| format!("`{}`", rule.as_str()))
                .collect::<Vec<_>>()
                .join(", ");

            writeln!(output, " {names}.").expect("writing to a string cannot fail");
        }
    }

    output.push_str("\n## Rules\n\n");

    for rule in FormatterRule::ALL {
        write_rule(&mut output, *rule);
    }

    output.pop();

    output
}

fn write_rule(output: &mut String, rule: FormatterRule) {
    let descriptor = rule.descriptor();

    writeln!(
        output,
        "### `{}`\n\n{}\n\nDefault: `{}`. Order: `{}`.\n",
        descriptor.name, descriptor.description, descriptor.enabled_by_default, descriptor.order,
    )
    .expect("writing to a string cannot fail");

    let decisions = descriptor.decisions.iter();

    for decision in decisions {
        writeln!(output, "- Own `{decision:?}` in `{:?}`.", decision.stage())
            .expect("writing to a string cannot fail");
    }

    for dependency in descriptor.dependencies {
        writeln!(
            output,
            "- Require `{}` for `{:?}`.",
            dependency.rule.as_str(),
            dependency.decision
        )
        .expect("writing to a string cannot fail");
    }

    for parameter in descriptor.parameters {
        let schema = parameter.schema();

        writeln!(
            output,
            "- Parameter `{}`: positive 16-bit integer, default `{}`.",
            schema.name, schema.default
        )
        .expect("writing to a string cannot fail");
    }

    if !descriptor.conflicts.is_empty() {
        let names = descriptor
            .conflicts
            .iter()
            .map(|rule| format!("`{}`", rule.as_str()))
            .collect::<Vec<_>>()
            .join(", ");

        writeln!(
            output,
            "- Resolve shared ownership with {names} by precedence."
        )
        .expect("writing to a string cannot fail");
    }

    output.push('\n');
}

#[cfg(test)]
mod tests {
    use super::{REFERENCE_PATH, reference};

    #[test]
    fn checked_in_reference_matches_the_rule_registry() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("xtask has a workspace root");

        let actual = std::fs::read_to_string(root.join(REFERENCE_PATH))
            .expect("formatter reference must exist");

        assert_eq!(actual, reference(), "run cargo xtask format reference");
    }
}
