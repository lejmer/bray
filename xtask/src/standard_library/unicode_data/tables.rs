use std::collections::BTreeMap;
use std::fmt::Write;

const SCALAR_COUNT: usize = 0x11_0000;
const LEAF_SIZE: usize = 32;
const BRANCH_SIZE: usize = 32;
const PROPERTY_NAMES: [&str; 3] = ["alphabetic", "numeric", "whitespace"];

pub(super) struct Tables {
    root: Vec<u16>,
    branches: Vec<u16>,
    properties: [Vec<u8>; 3],
}

impl Tables {
    pub(super) fn payloads(&self) -> [Vec<u8>; 5] {
        [
            self.root
                .iter()
                .flat_map(|value| value.to_le_bytes())
                .collect(),
            self.branches
                .iter()
                .flat_map(|value| value.to_le_bytes())
                .collect(),
            self.properties[0].clone(),
            self.properties[1].clone(),
            self.properties[2].clone(),
        ]
    }

    pub(super) fn new(properties: [&[(u32, u32)]; 3]) -> Self {
        let mut scalars = vec![0u8; SCALAR_COUNT];

        for (property, ranges) in properties.iter().enumerate() {
            for &(start, end) in *ranges {
                for scalar in &mut scalars[start as usize..=end as usize] {
                    *scalar |= 1 << property;
                }
            }
        }

        let mut leaves = Vec::new();
        let mut leaf_ids = BTreeMap::new();
        let mut indexes = Vec::new();

        for leaf in scalars.chunks_exact(LEAF_SIZE) {
            let next = leaf_ids.len();

            let id = *leaf_ids.entry(leaf).or_insert_with(|| {
                leaves.push(leaf);

                next
            });

            indexes.push(id);
        }

        let mut root = Vec::new();
        let mut branches = Vec::new();
        let mut branch_ids = BTreeMap::new();

        for branch in indexes.chunks_exact(BRANCH_SIZE) {
            let next = branch_ids.len();

            let id = *branch_ids.entry(branch).or_insert_with(|| {
                for &index in branch {
                    branches.push(u16::try_from(index).expect("Unicode leaf index must fit u16"));
                }

                next
            });

            root.push(u16::try_from(id).expect("Unicode branch index must fit u16"));
        }

        let properties = std::array::from_fn(|property| {
            let mut output = Vec::new();

            for leaf in &leaves {
                for group in leaf.chunks(8) {
                    let bits = group.iter().enumerate().fold(0, |bits, (bit, scalar)| {
                        bits | ((scalar >> property) & 1) << bit
                    });

                    output.push(bits);
                }
            }

            output
        });

        Self {
            root,
            branches,
            properties,
        }
    }

    pub(super) fn sizes(&self) -> [usize; 5] {
        [
            self.root.len() * 2,
            self.branches.len() * 2,
            self.properties[0].len(),
            self.properties[1].len(),
            self.properties[2].len(),
        ]
    }

    pub(super) fn render(&self, version: &str, revision: u32) -> String {
        let mut output = format!(
            "// Generated by `cargo xtask standard-library unicode generate`.\n// Unicode {version}, generator revision {revision}.\n// Two shared u16 index reads and one property byte read per scalar.\n\ntrusted internal module std.runtime.character;\n\n"
        );

        render_array(&mut output, "CLASSIFICATION_ROOT", "u16", &self.root, 16);

        render_array(
            &mut output,
            "CLASSIFICATION_BRANCHES",
            "u16",
            &self.branches,
            16,
        );

        for (name, property) in PROPERTY_NAMES.iter().zip(&self.properties) {
            render_array(
                &mut output,
                &format!("CLASSIFICATION_{}", name.to_uppercase()),
                "u8",
                property,
                4,
            );

            writeln!(output, "trusted internal func {name}(pos value: u32) -> bool\n{{\n    let leaf: usize = trusted classification_leaf(value);\n    let bit: usize = (value & 31) as usize;\n    let bits: usize = CLASSIFICATION_{}[leaf][bit / 8] as usize;\n\n    return (bits >> (bit % 8)) & 1 != 0;\n}}\n", name.to_uppercase()).expect("writing generated source to a string must succeed");
        }

        output.push_str("trusted internal func classification_leaf(pos value: u32) -> usize\n{\n    let root_index: usize = (value >> 10) as usize;\n    let branch: usize = CLASSIFICATION_ROOT[root_index / 16][root_index % 16] as usize;\n    let index: usize = branch * 32 + ((value >> 5) & 31) as usize;\n\n    return CLASSIFICATION_BRANCHES[index / 16][index % 16] as usize;\n}\n");

        bray_formatter::format_text(&output, &bray_formatter::FormatterConfiguration::default())
            .expect("generated Unicode source must format")
            .into_text()
    }
}

fn render_array<T: std::fmt::Display>(
    output: &mut String,
    name: &str,
    element: &str,
    values: &[T],
    columns: usize,
) {
    assert_eq!(
        values.len() % columns,
        0,
        "Unicode table rows must be complete"
    );

    writeln!(
        output,
        "internal static {name}: [[{element}; {columns}]; {}] =\n[",
        values.len() / columns
    )
    .expect("writing a table header must succeed");

    for row in values.chunks(columns) {
        output.push_str("    [");

        for value in row {
            write!(output, "{value}, ").expect("writing a table value must succeed");
        }

        output.pop();
        output.pop();
        output.push_str("],\n");
    }

    output.push_str("];\n\n");
}

#[cfg(test)]
mod tests {
    use super::{SCALAR_COUNT, Tables};
    use crate::standard_library::unicode_data::command::{load_inputs, property_ranges};

    #[test]
    fn every_code_point_matches_the_pinned_property_ranges() {
        let root = crate::workspace::root().expect("workspace must resolve");
        let inputs = load_inputs(&root).expect("pinned data must load");

        let ranges = [
            property_ranges(&inputs[0].contents, &["Alphabetic"]),
            property_ranges(&inputs[2].contents, &["Decimal", "Digit", "Numeric"]),
            property_ranges(&inputs[1].contents, &["White_Space"]),
        ]
        .map(|ranges| ranges.expect("property ranges must parse"));

        let tables = Tables::new([&ranges[0], &ranges[1], &ranges[2]]);

        for (property, ranges) in ranges.iter().enumerate() {
            let mut range = 0;

            for scalar in 0..SCALAR_COUNT {
                while range < ranges.len() && scalar > ranges[range].1 as usize {
                    range += 1;
                }

                let expected = range < ranges.len() && scalar >= ranges[range].0 as usize;
                let branch = usize::from(tables.root[scalar >> 10]);
                let leaf = usize::from(tables.branches[branch * 32 + ((scalar >> 5) & 31)]);
                let bit = scalar & 31;
                let actual = tables.properties[property][leaf * 4 + bit / 8] >> (bit % 8) & 1 != 0;

                assert_eq!(actual, expected, "property {property}, U+{scalar:04X}");
            }
        }

        assert_eq!(tables.sizes(), [2176, 5248, 1556, 1556, 1556]);

        assert_eq!(
            tables.render("17.0.0", 1),
            Tables::new([&ranges[0], &ranges[1], &ranges[2]]).render("17.0.0", 1)
        );
    }
}
